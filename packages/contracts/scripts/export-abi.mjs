#!/usr/bin/env node
// Exports the TreasuryReserveGuard ABI from Foundry's build output (out/) into a typed TS module.
// Usage: forge build && node scripts/export-abi.mjs   (or: pnpm --filter @tokeniq/contracts abi)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = join(root, "out", "TreasuryReserveGuard.sol", "TreasuryReserveGuard.json");
const outPath = join(root, "abi", "TreasuryReserveGuard.ts");

let artifact;
try {
  artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
} catch (err) {
  console.error(`Cannot read ${artifactPath}. Run \`forge build\` first.\n${err.message}`);
  process.exit(1);
}
if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
  console.error("Artifact has no ABI");
  process.exit(1);
}

const banner = [
  "// AUTO-GENERATED by scripts/export-abi.mjs from out/TreasuryReserveGuard.sol/TreasuryReserveGuard.json.",
  "// Do not edit by hand. Regenerate with: pnpm --filter @tokeniq/contracts abi",
  "",
].join("\n");
const body = `export const treasuryReserveGuardAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;

let output = banner + body;
try {
  // Format with the repository's Prettier config when Prettier is installed (keeps `format:check` green).
  const prettier = await import("prettier");
  const config = (await prettier.resolveConfig(outPath)) ?? {};
  output = await prettier.format(output, { ...config, parser: "typescript" });
} catch {
  // Prettier not available: the unformatted output is still valid TypeScript.
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output);
console.log(`Wrote ${outPath} (${artifact.abi.length} ABI entries)`);
